// Build/check the bounded Look inside Svelte trial. The generated bundle is checked in so Python users and
// installers need no Node runtime; CI verifies that source and generated code agree.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { performance } from 'node:perf_hooks';
import { compile } from 'svelte/compiler';
import { build } from 'esbuild';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), started = performance.now();
const result = await build({ absWorkingDir: root, entryPoints: ['ui/inside.js'], bundle: true, write: false,
  metafile: true, format: 'iife', globalName: 'HoardInside', minify: true, target: 'es2020', legalComments: 'inline',
  banner: { js: '// Generated by scripts/build_ui.mjs from ui/LookInside.svelte; edit its source, then rebuild.' },
  plugins: [{ name: 'svelte', setup(build) {
    build.onLoad({ filter: /\.svelte$/ }, args => {
      const compiled = compile(readFileSync(args.path, 'utf8'), { filename: args.path, generate: 'client', dev: false, css: 'injected' });
      if (compiled.warnings.length) throw new Error(compiled.warnings.map(warning => warning.message).join('\n'));
      return { contents: compiled.js.code, resolveDir: dirname(args.path) };
    });
  } }],
});
const bundled = [...new Set(Object.keys(result.metafile.inputs).filter(path => path.startsWith('node_modules/')).map(path => path.split('/')[1]))].sort();
const output = result.outputFiles[0].text, path = resolve(root, 'hoard/web/inside.generated.js');
const licenses = { clsx: 'license', 'esm-env': 'LICENSE', svelte: 'LICENSE.md' };
const licenseText = bundled.map(name => {
  if (!licenses[name]) throw new Error(`Add the bundled license for ${name}`);
  return name + '\n' + readFileSync(resolve(root, 'node_modules', name, licenses[name]), 'utf8');
}).join('\n\n');
const licensePath = resolve(root, 'hoard/web/inside.LICENSE.txt');

if (process.argv.includes('--check')) {
  if (readFileSync(licensePath, 'utf8') !== licenseText) throw new Error('Bundled UI licenses are stale: run node scripts/build_ui.mjs');
  if (readFileSync(path, 'utf8') !== output) throw new Error('Look inside bundle is stale: run node scripts/build_ui.mjs');
} else { writeFileSync(path, output); writeFileSync(licensePath, licenseText); }
process.stdout.write(JSON.stringify({ bytes: Buffer.byteLength(output), gzip_bytes: gzipSync(output).length,
  bundled, build_ms: Math.round(performance.now() - started) }) + '\n');
