"""Hoard's music for its videos: a track that loops with no seam, written out note by note and synthesised here.

    python promo/music/loop.py [OUT_FOLDER]        (default: build/promo/music)

Makes hoard-loop.wav (32 bars at 100 beats a minute, 76.8 seconds, 48 kHz stereo) and hoard-ending.wav (the
chord a video ends on, with its tail). Nothing is sampled, recorded or generated by a model: every sound is a sum of
sine waves, sawtooth waves and filtered noise, from the notes below (issue #291).

The loop has no seam because it's made as a circle: each note is written into the buffer at its time, wrapping past
the end back to the start, so a note held over the last bar line rings on into the first. The echo and the reverb
wrap the same way, and the filters run over three laps of the buffer and keep the middle one, so the last sample
leads into the first exactly as any sample leads into the next. A video can start anywhere in it and repeat it as
often as it needs.

Needs numpy and scipy (pip install numpy scipy), only for making the videos: Hoard itself doesn't use them.
"""
from __future__ import annotations

import sys
import wave
from pathlib import Path

import numpy as np
from scipy.signal import butter, fftconvolve, sosfilt

SR = 48000
BPM = 100
BEAT = 60 / BPM            # 0.6 s
BAR = 4 * BEAT             # 2.4 s
BARS = 32
L = int(round(BARS * BAR * SR))   # the loop, in samples
REPO = Path(__file__).resolve().parents[2]
rng = np.random.default_rng(1010)


# ---------------------------------------------------------------- sounds
def mtof(m: float) -> float:
    return 440.0 * 2 ** ((m - 69) / 12)


def t_(d: float) -> np.ndarray:
    return np.arange(int(d * SR)) / SR


def noise(d: float) -> np.ndarray:
    return rng.standard_normal(int(d * SR))


def lp(x, f, order=2):
    return sosfilt(butter(order, f, "low", fs=SR, output="sos"), x)


def hp(x, f, order=2):
    return sosfilt(butter(order, f, "high", fs=SR, output="sos"), x)


def bp(x, a, b, order=2):
    return sosfilt(butter(order, [a, b], "band", fs=SR, output="sos"), x)


def saw(f, t, detune=0.0):
    return 2 * ((f * (1 + detune) * t + rng.random()) % 1.0) - 1


def tail(x, ms=8):
    """A short fade at a sound's very end, so cutting it off never clicks."""
    k = min(len(x), int(SR * ms / 1000))
    x = np.array(x, float)
    x[-k:] *= np.linspace(1, 0, k)
    return x


def kick():
    t = t_(0.45)
    f = 47 + 85 * np.exp(-t * 30)
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 7.5)
    click = lp(noise(0.45), 3500) * np.exp(-t * 240) * 0.3
    return np.tanh(1.5 * (body + click)) * 0.9


def hat(d=0.06, decay=75):
    t = t_(d)
    return hp(noise(d), 7500, 4) * np.exp(-t * decay) * 0.45


def clap():
    t = t_(0.3)
    env = np.exp(-t * 22)
    for o in (0.0, 0.011, 0.023):
        env = env + 0.8 * np.exp(-np.clip(t - o, 0, None) * 170) * (t >= o)
    return bp(noise(0.3), 900, 3200) * env * 0.4


def shaker():
    t = t_(0.08)
    return bp(noise(0.08), 5000, 11000) * np.minimum(t / 0.01, 1) * np.exp(-t * 48) * 0.3


def pad_chord(notes, d, bright):
    t = t_(d)
    s = sum(saw(mtof(m), t, dt) for m in notes for dt in (-0.006, 0.0, 0.0065)) / (len(notes) * 3)
    env = np.minimum(t / 0.4, 1) * np.clip((d - t) / 0.5, 0, 1)
    return lp(s, bright) * env


def pluck(m, d=0.7, bright=1.0):
    t = t_(d)
    f = mtof(m)
    s = np.zeros(len(t))
    for h in range(1, 9):
        if f * h > 15000:
            break
        s += (1 / h) * np.exp(-t * (4 + h * 5 / bright)) * np.sin(2 * np.pi * f * h * t + h)
    return s * np.minimum(t / 0.003, 1) * 0.55


def bell(m, d=1.4):
    t = t_(d)
    f = mtof(m)
    s = sum(a * np.exp(-t * k) * np.sin(2 * np.pi * f * r * t)
            for r, a, k in ((1, 1, 3), (2.0, 0.4, 5), (2.76, 0.25, 7), (5.4, 0.12, 12)))
    return s * np.minimum(t / 0.002, 1) * 0.3


def bass(m, d):
    t = t_(d)
    f = mtof(m)
    s = 0.75 * np.sin(2 * np.pi * f * t) + 0.35 * lp(saw(f, t), 600)
    env = np.minimum(t / 0.006, 1) * (0.75 + 0.25 * np.exp(-t * 10)) * np.clip((d - t) / 0.03, 0, 1)
    return np.tanh(1.3 * s * env) * 0.8


# ---------------------------------------------------------------- the circle
class Bus:
    """One part's stereo buffer, a loop long: whatever runs past its end wraps round to its start."""

    def __init__(self):
        self.L = np.zeros(L)
        self.R = np.zeros(L)

    def add(self, sig, at, gain=1.0, pan=0.0):
        sig = tail(sig)
        gl = gain * np.cos((pan + 1) * np.pi / 4) * np.sqrt(2)
        gr = gain * np.sin((pan + 1) * np.pi / 4) * np.sqrt(2)
        i = int(round(at * SR)) % L
        idx = (i + np.arange(len(sig))) % L
        np.add.at(self.L, idx, sig * gl)
        np.add.at(self.R, idx, sig * gr)


def circular(fn, x):
    """Run a filter (or anything with memory) over the loop as if it had always been looping: three laps, keep the
    middle one."""
    return fn(np.concatenate([x, x, x]))[L:2 * L]


def wrap_convolve(x, ir):
    """Reverb on a loop: the tail of the last bars lands on the first ones."""
    y = fftconvolve(x, ir)
    out = y[:L].copy()
    for k in range(1, int(np.ceil(len(y) / L))):
        seg = y[k * L:(k + 1) * L]
        out[:len(seg)] += seg
    return out


# ---------------------------------------------------------------- the notes
# F major. Bars 0-15: I-V-vi-IV, light. Bars 16-31: vi-IV-I-V, full. Bar 31 turns back to bar 0.
CHORDS = {
    "F": dict(pad=[53, 57, 60, 64], root=41, arp=[65, 69, 72, 76]),
    "C": dict(pad=[48, 55, 62, 64], root=36, arp=[64, 67, 72, 74]),
    "Dm": dict(pad=[50, 57, 60, 65], root=38, arp=[62, 65, 69, 72]),
    "Bb": dict(pad=[46, 53, 57, 62], root=34, arp=[62, 65, 70, 74]),
}
PROG = ["F", "C", "Dm", "Bb"] * 4 + ["Dm", "Bb", "F", "C"] * 4
# a little tune over the full half, two bars at a time: (beat in the bar pair, note, beats long)
TUNE = [[(0, 77, 1.5), (1.5, 76, 0.5), (2, 72, 1), (3, 69, 1), (4, 70, 2), (6, 69, 1), (7, 65, 1)],
        [(0, 72, 1.5), (1.5, 74, 0.5), (2, 76, 1), (3, 77, 1), (4, 79, 3), (7, 76, 1)]]


def compose():
    drums, low, pad, keys, lead = Bus(), Bus(), Bus(), Bus(), Bus()
    kicks = []
    for bar, name in enumerate(PROG):
        t0 = bar * BAR
        ch = CHORDS[name]
        full = bar >= 16
        pad.add(pad_chord(ch["pad"], BAR + 0.5, 2300 if full else 1500), t0, 0.55)
        pad.add(pad_chord([n + 12 for n in ch["pad"][1:]], BAR + 0.5, 2600 if full else 1700), t0, 0.16, 0.3)
        order = [0, 1, 2, 3, 2, 1, 3, 2] if bar % 2 == 0 else [0, 2, 1, 3, 2, 3, 1, 2]
        steps = 16 if full and bar % 8 >= 4 else 8
        for s in range(steps):
            at = t0 + s * BAR / steps
            m = ch["arp"][order[(s // 2) % 8] if steps == 16 else order[s]] + (12 if steps == 16 and s % 4 == 3 else 0)
            keys.add(pluck(m, 0.6, 1.0 if full else 0.8), at, (0.62 if full else 0.5) * (1 if s % 2 == 0 else 0.8),
                     -0.25 if s % 2 else 0.25)
        for b in range(4):
            at = t0 + b * BEAT
            if full or b in (0, 2):
                drums.add(kick(), at, 0.95)
                kicks.append(at)
            drums.add(hat(), at + BEAT / 2, 0.5 if full else 0.38, 0.2)
            if full and b in (1, 3):
                drums.add(clap(), at, 0.65)
            if full and bar % 8 >= 4:
                for k in range(4):
                    drums.add(shaker(), at + k * BEAT / 4, 0.45 if k % 2 else 0.28, -0.3)
        r = ch["root"]
        if full:
            pattern = [0, 0, 12, 0, 0, 12, 0, 12] if bar % 2 == 0 else [0, 0, 12, 0, 0, 0, 12, 7]
            for s in range(8):
                low.add(bass(r + pattern[s], 0.27), t0 + s * BAR / 8, 0.7)
        else:
            low.add(bass(r, BAR / 2 - 0.05), t0, 0.6)
            low.add(bass(r + (7 if bar % 2 else 12), BAR / 2 - 0.05), t0 + BAR / 2, 0.55)
        if full and bar % 2 == 0:
            for beat, m, d in TUNE[(bar // 2) % 2]:
                lead.add(bell(m, max(0.9, d * BEAT + 0.6)), t0 + beat * BEAT, 0.42, 0.15)
    # bar 31's turnaround: a snare-ish roll that leads back into bar 0 (and on, round the circle)
    for k in range(8):
        drums.add(clap() * 0.7, 31 * BAR + 2 * BEAT + k * BEAT / 4, 0.18 + 0.5 * k / 7, (k % 2 - 0.5) * 0.3)
    # bar 15: the light half lifts into the full one
    for k in range(4):
        drums.add(clap(), 15 * BAR + 3 * BEAT + k * BEAT / 4, 0.25 + 0.4 * k / 3)
    return drums, low, pad, keys, lead, kicks


def mix(drums, low, pad, keys, lead, kicks):
    t = np.arange(L) / SR
    duck = np.ones(L)
    for kt in kicks:   # the pad and bass dip under each kick, round the circle too
        dt = (t - kt) % (BARS * BAR)
        duck = np.minimum(duck, 1 - 0.55 * np.exp(-dt / 0.1) * (dt < 0.35))
    # dotted-eighth ping-pong echo on the keys, wrapping
    d = int(0.75 * BEAT * SR)
    kl, kr = keys.L.copy(), keys.R.copy()
    src_l, src_r = circular(lambda x: lp(x, 3500), keys.L), circular(lambda x: lp(x, 3500), keys.R)
    for k in range(1, 5):
        g = 0.3 ** k
        if k % 2:
            kl += np.roll(src_r, d * k) * g
        else:
            kr += np.roll(src_l, d * k) * g
    # reverb: decaying noise, a little different per side
    tt = np.arange(int(2.6 * SR)) / SR
    irs = []
    for pre in (0.012, 0.017):
        ir = lp(rng.standard_normal(len(tt)), 6500) * np.exp(-tt * 2.6)
        ir[:int(pre * SR)] = 0
        irs.append(ir / np.sqrt(np.sum(ir ** 2)))
    send_l = 0.25 * kl + 0.18 * pad.L * duck + 0.35 * lead.L
    send_r = 0.25 * kr + 0.18 * pad.R * duck + 0.35 * lead.R
    wet_l, wet_r = wrap_convolve(send_l, irs[0]), wrap_convolve(send_r, irs[1])
    out = []
    for D, B, P, K, M, W in ((drums.L, low.L, pad.L, kl, lead.L, wet_l), (drums.R, low.R, pad.R, kr, lead.R, wet_r)):
        x = D * 0.55 + B * duck * 0.6 + P * duck * 0.75 + K * 0.8 + M * 0.7 + W * 0.4
        out.append(circular(lambda s: hp(s, 28), x))
    peak = max(np.abs(out[0]).max(), np.abs(out[1]).max())
    return [np.tanh(1.6 * s / peak) / np.tanh(1.6) * 0.89 for s in out], peak


def ending(peak):
    """The chord a video ends on: F major, a bass note and a falling bell, with its own tail. Played over the loop's
    last moment (the loop fading out under it), on a bar line."""
    n = int(5.5 * SR)
    bus_l, bus_r = np.zeros(n), np.zeros(n)

    def put(sig, at, g, pan=0.0):
        sig = tail(sig)[: n - int(at * SR)]
        i = int(at * SR)
        bus_l[i:i + len(sig)] += sig * g * np.cos((pan + 1) * np.pi / 4) * np.sqrt(2)
        bus_r[i:i + len(sig)] += sig * g * np.sin((pan + 1) * np.pi / 4) * np.sqrt(2)

    put(pad_chord(CHORDS["F"]["pad"] + [69, 72], 5.0, 2400), 0, 0.75)
    put(bass(29, 3.2) * np.exp(-t_(3.2) * 0.9), 0, 0.9)
    put(kick(), 0, 0.9)
    for i, m in enumerate([65, 69, 72, 76, 81]):
        put(pluck(m, 1.8), i * 0.035, 0.7, (i - 2) * 0.2)
    for i, m in enumerate([84, 81, 77]):
        put(bell(m, 1.8), 0.6 + i * 0.3, 0.3, (i - 1) * 0.3)
    tt = np.arange(int(2.6 * SR)) / SR
    ir = lp(rng.standard_normal(len(tt)), 6500) * np.exp(-tt * 2.6)
    ir /= np.sqrt(np.sum(ir ** 2))
    fade = np.clip((n - np.arange(n)) / (1.2 * SR), 0, 1) ** 1.5
    res = []
    for b in (bus_l, bus_r):
        x = hp(b + fftconvolve(b * 0.3, ir)[:n] * 0.4, 28) * fade
        res.append(np.tanh(1.6 * x / peak) / np.tanh(1.6) * 0.89)
    return res


def write(path: Path, left, right):
    data = (np.clip(np.stack([left, right], 1), -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    parts = compose()
    (left, right), peak = mix(*parts)
    write(out / "hoard-loop.wav", left, right)
    write(out / "hoard-ending.wav", *ending(peak))
    print(f"{out / 'hoard-loop.wav'}: {L / SR:.1f} s, {BARS} bars at {BPM} bpm; {out / 'hoard-ending.wav'}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "build" / "promo" / "music")
