"""Make Hoard's videos: the promos (issue #273) and the help videos (issue #274), from the films in promo/films/.

    python promo/build.py FILM [FILM...] [--lang=en,ja,ko] [--shape=landscape,portrait] [--fps=60] [--workers=2]
                          [--shots=build/shots] [--out=build/promo/out] [--frames-only] [--keep-frames]
                          [--preview=1.5,6,12]   (pictures of those moments, in the first language and shape)

FILM is a file's name in promo/films/ without .json (promo-short). Before this, make the screenshots and the music:

    python scripts/screenshots.py PRODUCTS_FOLDER build/shots --themes=dark,light --lang=en --regions=promo/regions.json
    (and again with --lang=ja and --lang=ko)
    python promo/music/loop.py

Each video is drawn by promo/video/film.html, one frame at a time, in Chromium (Playwright), and put together with
the music by ffmpeg: build/promo/out/hoard-<film>-<lang>-<shape>.mp4. Nothing in them is generated by a model: the
pictures are Hoard's own screens and shapes drawn in HTML and SVG, the music is promo/music/loop.py's notes.

Every frame is checked as it's drawn: a video with a highlight that would run off the edge, or a close-up over what
it shows, isn't made, and the build says where (and goes on to the next). A film made only in some shapes says so
("shapes": the help videos are landscape only). Each video's frames are deleted once it's made, unless --keep-frames.
"""
from __future__ import annotations

import json
import math
import multiprocessing as mp
import re
import shutil
import subprocess
import sys
import wave
from pathlib import Path

try:
    import numpy as np
except ImportError:   # (promo/requirements.txt: only the music and the grain need it)
    np = None

REPO = Path(__file__).resolve().parents[1]
PROMO = REPO / "promo"
BUILD = REPO / "build" / "promo"
SIZES = {"landscape": (1920, 1080), "portrait": (1080, 1920)}
SR = 48000


def heap_parts() -> dict:
    """The Heap as hoard/heap.py draws it, so the videos' logo is the one Hoard has everywhere: where each box lands
    (in its 64 x 64 square), its colour and what's on it, and the logo's SVG, its boxes and its wordmark."""
    sys.path.insert(0, str(REPO))
    from hoard import heap
    boxes = []
    for p in heap.layout(heap.FULL):
        s, k = p["size"], p["scale"]
        extra = ""
        if p["box"] == "gold":
            extra = f'<path d="{heap._sparkle(s)}" fill="{heap.SPARK}"/>'
        elif p["box"] == "projects":
            extra = (f'<path d="{heap._cube(s)}" fill="none" stroke="{heap.CAVE}" stroke-width="{1.5 * k:.2f}" '
                     'stroke-linejoin="round" stroke-linecap="round"/>')
        boxes.append({**p, "fill": heap.GOLD if p["box"] == "gold" else heap.COLOURS[p["box"]],
                      "line": heap.LINE * k, "round": heap.ROUND * k, "extra": extra})
    return {"boxes": boxes, "svg": heap.boxes_svg(heap.FULL), "word": heap.word()}


def grain() -> None:
    """The film grain laid over every frame: random noise, made once."""
    path = BUILD / "grain.png"
    if path.is_file():
        return
    from PIL import Image
    BUILD.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(7)
    Image.fromarray(rng.normal(128, 40, (256, 256)).clip(0, 255).astype("uint8"), "L").save(path)


def setup_for(film: dict, lang: str, shape: str, shots: Path) -> dict:
    regions = {}
    for s in film["scenes"]:
        if s.get("image"):
            box = shots / f"{s['image']}-{film.get('theme', 'dark')}{'' if lang == 'en' else '-' + lang}.json"
            if not box.is_file():
                sys.exit(f"{box} isn't there: make the screenshots with --regions=promo/regions.json first")
            regions[s["image"]] = json.loads(box.read_text("utf-8"))
    return {"film": film, "lang": lang, "shape": shape, "regions": regions, "heap": heap_parts(),
            "shots": shots.resolve().as_uri()}


def render_part(job) -> list[str]:
    """One worker's share of the frames (every n-th): draws each, takes its picture, checks it."""
    cfg, frames, fps, folder, worker, workers = job
    from playwright.sync_api import sync_playwright
    w, h = SIZES[cfg["shape"]]
    problems = []
    with sync_playwright() as pw:
        browser = pw.chromium.launch(args=["--disable-lcd-text", "--font-render-hinting=none"])
        page = browser.new_page(viewport={"width": w, "height": h}, device_scale_factor=1)
        page.on("pageerror", lambda e: problems.append(f"page error: {e}"))
        page.goto((PROMO / "video" / "film.html").as_uri())
        page.evaluate("document.fonts.ready")
        page.evaluate("cfg => window.setup(cfg)", cfg)
        page.evaluate("Promise.all([...document.images].map(i => i.decode().catch(() => null)))")
        page.wait_for_timeout(300)
        for i in range(worker, frames, workers):
            out = folder / f"f{i:05d}.jpg"
            page.evaluate("t => window.seek(t)", i / fps)
            if i % (fps // 4) == 0:
                problems += [f"{i / fps:.2f}s: {p}" for p in page.evaluate("window.checkFrame()")]
            if not out.is_file():
                page.screenshot(path=str(out), type="jpeg", quality=94)
        browser.close()
    return problems


def preview(name: str, lang: str, shape: str, shots: Path, times: list[float]) -> None:
    """Pictures of a few moments of a film, to look at while writing it: build/promo/preview/<film>-...-<t>.png."""
    from playwright.sync_api import sync_playwright
    film = json.loads((PROMO / "films" / f"{name}.json").read_text("utf-8"))
    cfg = setup_for(film, lang, shape, shots)
    w, h = SIZES[shape]
    out = BUILD / "preview"
    out.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as pw:
        browser = pw.chromium.launch(args=["--disable-lcd-text", "--font-render-hinting=none"])
        page = browser.new_page(viewport={"width": w, "height": h})
        page.on("pageerror", lambda e: print("page error:", e))
        page.goto((PROMO / "video" / "film.html").as_uri())
        page.evaluate("document.fonts.ready")
        info = page.evaluate("cfg => window.setup(cfg)", cfg)
        page.evaluate("Promise.all([...document.images].map(i => i.decode().catch(() => null)))")
        for t in times:
            page.evaluate("t => window.seek(t)", t)
            for p in page.evaluate("window.checkFrame()"):
                print(f"{t:.2f}s: {p}")
            page.screenshot(path=str(out / f"{name}-{lang}-{shape}-{t:05.2f}.png"))
        browser.close()
    print(f"{info['duration']:.1f} s; {', '.join(info['warnings']) or 'no warnings'}")


def read_wav(path: Path) -> np.ndarray:
    with wave.open(str(path)) as w:
        return np.frombuffer(w.readframes(w.getnframes()), "<i2").reshape(-1, 2).astype(float) / 32767


def soundtrack(film: dict, duration: float, out: Path) -> None:
    """The loop from the film's starting bar, as long as the video, with the ending chord on the end card."""
    music = BUILD / "music"
    if not (music / "hoard-loop.wav").is_file():
        subprocess.run([sys.executable, str(PROMO / "music" / "loop.py"), str(music)], check=True)
    loop, end = read_wav(music / "hoard-loop.wav"), read_wav(music / "hoard-ending.wav")
    bar = 4 * 60 / film["bpm"]
    start = int(round(film["music"].get("start_bar", 0) * bar * SR)) % len(loop)
    n = int(math.ceil(duration * SR))
    reps = int(math.ceil((start + n) / len(loop))) + 1
    track = np.tile(loop, (reps, 1))[start:start + n].copy()
    ends = [i for i, s in enumerate(film["scenes"]) if s.get("ending")]
    t_end = sum(s["bars"] for s in film["scenes"][:ends[0]]) * bar if ends else None   # where the ending chord goes
    if t_end is not None:
        i = int(round(t_end * SR))
        fade = int(.12 * SR)
        track[i:i + fade] *= np.linspace(1, 0, min(fade, n - i))[:, None]
        track[i + fade:] = 0
        k = min(len(end), n - i)
        track[i:i + k] += end[:k]
    f = int(.8 * SR)
    track[-f:] *= np.linspace(1, 0, f)[:, None] ** 1.5
    raw = out.with_suffix(".raw.wav")
    with wave.open(str(raw), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(track, -1, 1) * 32767).astype("<i2").tobytes())
    # loudness: about -16 LUFS for social sites (a help video's music is quieter), peaks under -1.5 dB (two passes,
    # so it's measured, not guessed)
    lufs = film["music"].get("lufs", -16)
    meas = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(raw), "-af",
                           f"loudnorm=I={lufs}:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"],
                          capture_output=True, text=True).stderr
    m = json.loads(meas[meas.rindex("{"):meas.rindex("}") + 1])
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(raw), "-af",
                    f"loudnorm=I={lufs}:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
                    f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}"
                    ":linear=true", "-ar", str(SR), str(out)], check=True)
    raw.unlink()


def speaks(film, lang: str) -> bool:
    """Whether a film has its words in this language (every set of words: a dict with "en")."""
    if isinstance(film, dict):
        return lang in film if "en" in film else all(speaks(v, lang) for v in film.values())
    return all(speaks(v, lang) for v in film) if isinstance(film, list) else True


def make(name: str, lang: str, shape: str, fps: int, workers: int, shots: Path, outdir: Path, frames_only: bool,
         keep_frames: bool = False) -> list[str]:
    """Make one video; what was wrong with its frames, if anything (then it isn't made)."""
    film = json.loads((PROMO / "films" / f"{name}.json").read_text("utf-8"))
    if not speaks(film, lang):
        print(f"{name}-{lang}: not made, its words aren't in that language yet")
        return []
    if shape not in film.get("shapes", ("landscape", "portrait")):
        return []   # (the help videos are landscape only)
    cfg = setup_for(film, lang, shape, shots)
    tag = f"{name}-{lang}-{shape}"
    folder = BUILD / "frames" / tag
    folder.mkdir(parents=True, exist_ok=True)
    bar = 4 * 60 / film["bpm"]
    duration = sum(s["bars"] for s in film["scenes"]) * bar + film.get("tail", 0)
    frames = int(round(duration * fps))
    print(f"{tag}: {duration:.1f} s, {frames} frames")
    with mp.get_context("spawn").Pool(workers) as pool:
        problems = sum(pool.map(render_part, [(cfg, frames, fps, folder, k, workers) for k in range(workers)]), [])
    if problems:
        print(f"{tag}: not made:\n  " + "\n  ".join(sorted(set(problems))))
        return [tag]
    if frames_only:
        return []
    outdir.mkdir(parents=True, exist_ok=True)
    audio = BUILD / f"{tag}.wav"
    soundtrack(film, frames / fps, audio)
    video = outdir / f"hoard-{tag}.mp4"
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-framerate", str(fps),
                    "-i", str(folder / "f%05d.jpg"), "-i", str(audio), "-map", "0:v", "-map", "1:a",
                    "-c:v", "libx264", "-preset", "veryfast", "-crf", "18", "-pix_fmt", "yuv420p",
                    "-profile:v", "high", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "256k",
                    "-shortest", str(video)], check=True)
    audio.unlink()
    if not keep_frames:   # (--keep-frames keeps them, for drawing only some of them again)
        shutil.rmtree(folder)
    print(f"  {video}")
    return []


def main(argv: list[str]) -> None:
    names = [a for a in argv if not a.startswith("--")]
    opts = dict(a[2:].split("=", 1) if "=" in a else (a[2:], "1") for a in argv if a.startswith("--"))
    if not names:
        sys.exit(__doc__)
    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg isn't installed")
    grain()
    if "preview" in opts:
        lang, shape = opts.get("lang", "en").split(",")[0], opts.get("shape", "landscape").split(",")[0]
        return preview(names[0], lang, shape, Path(opts.get("shots", REPO / "build" / "shots")),
                       [float(x) for x in opts["preview"].split(",")])
    failed = []
    for name in names:
        for lang in opts.get("lang", "en").split(","):
            for shape in opts.get("shape", "landscape").split(","):
                failed += make(name, lang, shape, int(opts.get("fps", 60)), int(opts.get("workers", 2)),
                               Path(opts.get("shots", REPO / "build" / "shots")), Path(opts.get("out", BUILD / "out")),
                               "frames-only" in opts, "keep-frames" in opts)
    if failed:
        sys.exit(f"Not made: {', '.join(failed)}")


if __name__ == "__main__":
    main(sys.argv[1:])
